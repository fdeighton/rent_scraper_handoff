# Build the Fitzrovia Agent Windows installer.
#
#   cd agent
#   pwsh build/build_windows.ps1 -Version 0.1.0 `
#       -SupabaseUrl "https://<ref>.supabase.co" `
#       -AuthorizeUrl "https://your-site/authorize.html"
#
# Produces: agent/build/Output/FitzroviaAgent-<version>-setup.exe
# Prereqs:  pip install -r requirements.txt pyinstaller ; Inno Setup (iscc on PATH).
# NOTE: only NON-secret config is baked in. The DB token is delivered at runtime via
#       pairing; the Anthropic key lives on the hub — neither is compiled into the installer.
#
# CODE SIGNING (recommended — see build/it-security-note.md):
#   Pass -SignThumbprint (cert in the Windows cert store) OR -SignPfx (+ -SignPfxPassword)
#   to Authenticode-sign the agent exe AND the installer. Without a signing arg the build
#   is UNSIGNED (we never fake-sign). Once signed, IT can allowlist by PUBLISHER certificate
#   instead of per-file hash, which stops the "unsigned/changing binary" Sentinel flags.
param(
  [string]$Version = "0.1.0",
  [Parameter(Mandatory = $true)][string]$SupabaseUrl,
  [Parameter(Mandatory = $true)][string]$AuthorizeUrl,
  # PUBLIC anon key (NEXT_PUBLIC_SUPABASE_ANON_KEY). It is the REQUIRED Supabase `apikey`
  # header — WITHOUT it the agent silently falls back to in-memory DEMO mode and never
  # registers/heartbeats/claims a job. It is not a secret (it ships in every hub page),
  # so it is baked; the scoped worker token still comes at runtime via pairing.
  [Parameter(Mandatory = $true)][string]$AnonKey,
  [string]$HubUrl = "",              # hub origin for /api/comp-scrape/extract; blank = derive from AuthorizeUrl
  [int]$UpdateCheckSeconds = 3600,   # how often a running agent re-checks for updates; lower it for demos
  [string]$SignThumbprint = "",      # SHA1 thumbprint of a cert in the Windows cert store
  [string]$SignPfx = "",             # OR path to a .pfx cert file
  [string]$SignPfxPassword = "",     # password for the .pfx (if any)
  [string]$TimestampUrl = "http://timestamp.digicert.com"
)
$ErrorActionPreference = "Stop"
$AgentDir = Split-Path $PSScriptRoot -Parent
Set-Location $AgentDir

# --- optional Authenticode signing -------------------------------------------
$script:SignTool = $null
if ($SignThumbprint -or $SignPfx) {
  $script:SignTool = (Get-Command signtool.exe -ErrorAction SilentlyContinue).Source
  if (-not $script:SignTool) {
    $script:SignTool = Get-ChildItem "C:\Program Files (x86)\Windows Kits\10\bin\*\x64\signtool.exe" `
      -ErrorAction SilentlyContinue | Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
  }
  if (-not $script:SignTool) { throw "Signing requested but signtool.exe not found (install the Windows 10/11 SDK)." }
}
function Invoke-Sign([string]$File) {
  if (-not $script:SignTool) { return }   # unsigned build — no fake signing
  $a = @('sign', '/fd', 'SHA256', '/tr', $TimestampUrl, '/td', 'SHA256')
  if ($SignPfx) { $a += @('/f', $SignPfx); if ($SignPfxPassword) { $a += @('/p', $SignPfxPassword) } }
  else          { $a += @('/sha1', $SignThumbprint) }
  $a += $File
  Write-Host "   signing $File"
  & $script:SignTool @a
  if ($LASTEXITCODE -ne 0) { throw "signtool failed for $File" }
}

Write-Host "1/5  Baking non-secret config -> build/agent.env"
@"
SUPABASE_URL=$SupabaseUrl
SUPABASE_ANON_KEY=$AnonKey
AGENT_AUTHORIZE_URL=$AuthorizeUrl
AGENT_HUB_URL=$HubUrl
AGENT_VERSION=$Version
AGENT_UPDATE_CHECK_SECONDS=$UpdateCheckSeconds
HEADLESS=true
"@ | Out-File -FilePath "build/agent.env" -Encoding ascii

Write-Host "2/5  Writing Windows version resource -> build/version_info.txt"
$vp = @($Version -split '\.'); while ($vp.Count -lt 4) { $vp += '0' }
$v4 = "$($vp[0]), $($vp[1]), $($vp[2]), $($vp[3])"
@"
# Auto-generated by build_windows.ps1 — do not edit. Embedded in FitzroviaAgent.exe.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($v4), prodvers=($v4),
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
  ),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Fitzrovia'),
      StringStruct('FileDescription', 'Fitzrovia Agent'),
      StringStruct('FileVersion', '$Version'),
      StringStruct('InternalName', 'FitzroviaAgent'),
      StringStruct('LegalCopyright', 'Copyright (c) Fitzrovia'),
      StringStruct('OriginalFilename', 'FitzroviaAgent.exe'),
      StringStruct('ProductName', 'Fitzrovia Agent'),
      StringStruct('ProductVersion', '$Version')
    ])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@ | Out-File -FilePath "build/version_info.txt" -Encoding ascii

Write-Host "3/5  Generating icon.ico from assets/icon.png"
python -c "from PIL import Image; Image.open('assets/icon.png').save('assets/icon.ico', sizes=[(16,16),(32,32),(48,48),(64,64),(128,128),(256,256)])"

Write-Host "4/5  PyInstaller bundle"
pyinstaller build/agent.spec --noconfirm --distpath dist --workpath build/work
Invoke-Sign "dist/FitzroviaAgent/FitzroviaAgent.exe"   # sign the app exe BEFORE Inno packs it

Write-Host "5/5  Inno Setup installer"
iscc "/DMyAppVersion=$Version" build/installer.iss
Invoke-Sign "build/Output/FitzroviaAgent-$Version-setup.exe"   # sign the installer

Write-Host "Done -> build/Output/FitzroviaAgent-$Version-setup.exe"
if (-not $script:SignTool) {
  Write-Host "WARNING: build is UNSIGNED. Pass -SignThumbprint or -SignPfx to sign (see build/it-security-note.md)." -ForegroundColor Yellow
}
